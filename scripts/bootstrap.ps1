function Stop-WithMessage([string]$Message) {
    [Console]::Error.WriteLine("Error: $Message")
    exit 1
}

function New-SecureHexSecret {
    $bytes = New-Object byte[] 48
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return [System.BitConverter]::ToString($bytes).Replace("-", "").ToLowerInvariant()
}

function New-StableMediaRootId {
    $bytes = New-Object byte[] 8
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return "root_" + [System.BitConverter]::ToString($bytes).Replace("-", "").ToLowerInvariant()
}

function ConvertTo-DotEnvLiteral([string]$Value) {
    if ($Value -match '[\x00-\x1f\x7f]') {
        throw "A local configuration value contains an unsupported control character."
    }
    return "'" + $Value.Replace("'", "\'") + "'"
}

function Test-InteractiveInput {
    if (-not [Environment]::UserInteractive) { return $false }
    try { return -not [Console]::IsInputRedirected } catch { return $false }
}

function Select-NativeMediaFolder {
    if (-not (Test-InteractiveInput) -or $env:OS -ne "Windows_NT") { return $null }
    try {
        Add-Type -AssemblyName System.Windows.Forms -ErrorAction Stop
        $dialog = [System.Windows.Forms.FolderBrowserDialog]::new()
        try {
            $dialog.Description = "Choose a folder BlueReel may read as source media"
            if ($dialog.PSObject.Properties.Name -contains "UseDescriptionForTitle") {
                $dialog.UseDescriptionForTitle = $true
            }
            if ($dialog.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {
                return $dialog.SelectedPath
            }
        } finally {
            $dialog.Dispose()
        }
    } catch {
        Write-Warning "A native folder dialog is unavailable in this PowerShell host; use typed-path selection instead."
    }
    return $null
}

function Read-InteractiveMediaRoots {
    $selected = [System.Collections.Generic.List[object]]::new()
    while ($true) {
        $choice = (Read-Host "Choose an approved media root: [B]rowse, [T]ype a path, or [S]kip").Trim().ToUpperInvariant()
        if ($choice -eq "S") { break }
        $path = $null
        if ($choice -eq "B") {
            $path = Select-NativeMediaFolder
            if (-not $path) {
                Write-Host "No folder was selected."
                continue
            }
        } elseif ($choice -eq "T") {
            $path = (Read-Host "Host folder path").Trim()
            if (-not $path) { continue }
        } else {
            Write-Host "Enter B, T, or S."
            continue
        }
        $label = (Read-Host "Friendly display name (press Enter to use the folder name)").Trim()
        $selected.Add([pscustomobject]@{ Path = $path; Label = $label })
        $more = (Read-Host "Add another approved media root? [y/N]").Trim()
        if ($more -notmatch '^(?i:y|yes)$') { break }
    }
    return @($selected)
}

function Resolve-SelectedMediaRoot([string]$Path, [string]$Label) {
    if ([string]::IsNullOrWhiteSpace($Path) -or $Path -match '[\x00-\x1f\x7f]') {
        throw "A selected media path is empty or contains an unsupported control character."
    }
    if ($Path.Contains('$')) {
        throw "Media paths containing a dollar sign are unsupported because Docker Compose interpolates that character. Select a dedicated wrapper folder without a dollar sign."
    }
    $item = Get-Item -LiteralPath $Path -Force -ErrorAction Stop
    if (-not $item.PSIsContainer) { throw "The selected media path is not a directory: $Path" }
    if (($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw "The selected media root is a link or reparse point. Select its real directory instead: $Path"
    }
    $resolved = [System.IO.Path]::GetFullPath($item.FullName).TrimEnd('\', '/')
    $root = [System.IO.Path]::GetPathRoot($item.FullName).TrimEnd('\', '/')
    if ($resolved.Equals($root, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "A whole drive or filesystem root is too broad. Select a dedicated media directory instead: $Path"
    }
    try {
        $enumerator = [System.IO.Directory]::EnumerateFileSystemEntries($resolved).GetEnumerator()
        try { $null = $enumerator.MoveNext() } finally { if ($enumerator -is [System.IDisposable]) { $enumerator.Dispose() } }
    } catch {
        throw "The selected media directory is not readable: $Path"
    }
    $labelWasExplicit = -not [string]::IsNullOrWhiteSpace($Label)
    $displayName = $Label.Trim()
    if (-not $displayName) { $displayName = Split-Path -Leaf $resolved }
    if (-not $displayName) { $displayName = "Media" }
    if ($displayName.Length -gt 80 -or $displayName -match '[\x00-\x1f\x7f]') {
        throw "A media-root display name must be 1-80 printable characters."
    }
    if ($displayName.Contains('$')) {
        throw "Media-root display names cannot contain a dollar sign because Docker Compose interpolates that character."
    }
    return [pscustomobject]@{
        HostPath = $resolved.Replace('\', '/')
        DisplayName = $displayName
        LabelWasExplicit = $labelWasExplicit
    }
}

function Read-MediaRootRegistry {
    if (-not (Test-Path -LiteralPath $MediaRootRegistryFile -PathType Leaf)) { return @() }
    $lines = [System.IO.File]::ReadAllLines($MediaRootRegistryFile)
    if ($lines.Count -eq 0 -or $lines[0] -ne $MediaRootRegistryHeader) {
        throw "The local media-root registry is not managed by this bootstrap script: $MediaRootRegistryFile"
    }
    $roots = [System.Collections.Generic.List[object]]::new()
    $ids = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    $targets = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    foreach ($line in $lines | Select-Object -Skip 1) {
        if (-not $line) { continue }
        $fields = $line.Split("`t", 4)
        $expectedTarget = if ($roots.Count -eq 0) { "/media" } else { "/media-roots/$($fields[0])" }
        if ($fields.Count -ne 4 -or $fields[0] -notmatch '^[a-z0-9][a-z0-9_-]{0,63}$' -or
            ($roots.Count -eq 0 -and $fields[0] -ne "primary") -or
            ($roots.Count -gt 0 -and $fields[0] -eq "primary") -or
            $fields[2] -ne $expectedTarget -or [string]::IsNullOrWhiteSpace($fields[1]) -or
            [string]::IsNullOrWhiteSpace($fields[3]) -or -not $ids.Add($fields[0]) -or -not $targets.Add($fields[2])) {
            throw "The local media-root registry is invalid: $MediaRootRegistryFile"
        }
        $roots.Add([pscustomobject]@{
            Id = $fields[0]
            DisplayName = $fields[1]
            ContainerPath = $fields[2]
            HostPath = $fields[3]
        })
    }
    return @($roots)
}

function Test-ManagedComposeOverride {
    if (-not (Test-Path -LiteralPath $ComposeOverrideFile -PathType Leaf)) { return $false }
    return (Get-Content -LiteralPath $ComposeOverrideFile -TotalCount 1) -eq $GeneratedOverrideMarker
}

function Update-DotEnvContent([string]$Content, [System.Collections.IDictionary]$Updates) {
    $newline = if ($Content.Contains("`r`n")) { "`r`n" } else { "`n" }
    foreach ($key in $Updates.Keys) {
        $replacement = "$key=$($Updates[$key])"
        $pattern = "(?m)^" + [regex]::Escape($key) + "=.*$"
        if ([regex]::IsMatch($Content, $pattern)) {
            $Content = [regex]::Replace($Content, $pattern, [System.Text.RegularExpressions.MatchEvaluator]{ param($match) $replacement })
        } else {
            if ($Content.Length -gt 0 -and -not $Content.EndsWith("`n")) { $Content += $newline }
            $Content += $replacement + $newline
        }
    }
    return $Content
}

function Write-AtomicUtf8([string]$Path, [string]$Content) {
    $directory = Split-Path -Parent $Path
    [System.IO.Directory]::CreateDirectory($directory) | Out-Null
    $temporary = Join-Path $directory ("." + [System.IO.Path]::GetFileName($Path) + ".tmp." + [guid]::NewGuid().ToString("N"))
    try {
        [System.IO.File]::WriteAllText($temporary, $Content, [System.Text.UTF8Encoding]::new($false))
        Move-Item -LiteralPath $temporary -Destination $Path -Force
    } finally {
        if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary -Force }
    }
}

function Read-DotEnv([string]$Path) {
    $values = @{}
    foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
        $trimmed = $line.Trim()
        if ($trimmed.Length -eq 0 -or $trimmed.StartsWith("#")) { continue }
        $separator = $trimmed.IndexOf("=")
        if ($separator -lt 1) { continue }
        $key = $trimmed.Substring(0, $separator).Trim()
        $value = $trimmed.Substring($separator + 1).Trim()
        if ($value.StartsWith("'") -and $value.EndsWith("'")) {
            $value = $value.Substring(1, $value.Length - 2)
            $value = $value.Replace("\'", "'")
        } elseif ($value.StartsWith('"') -and $value.EndsWith('"')) {
            $value = $value.Substring(1, $value.Length - 2)
        }
        $values[$key] = $value
    }
    return $values
}

function Resolve-ConfiguredPath([string]$Value) {
    if ([System.IO.Path]::IsPathRooted($Value)) {
        return [System.IO.Path]::GetFullPath($Value)
    }
    return [System.IO.Path]::GetFullPath((Join-Path $RepositoryRoot $Value))
}

function Set-MediaRootConfiguration([object[]]$Selections, [hashtable]$ResolvedState) {
    if ($Selections.Count -eq 0) { return $false }
    if ((Test-Path -LiteralPath $ComposeOverrideFile) -and -not (Test-ManagedComposeOverride)) {
        Stop-WithMessage "compose.override.yml already exists and is not managed by BlueReel. It was not overwritten; merge approved media roots deliberately."
    }

    try { $existing = @(Read-MediaRootRegistry) } catch { Stop-WithMessage $_.Exception.Message }
    $resolvedSelections = [System.Collections.Generic.List[object]]::new()
    foreach ($selection in $Selections) {
        try {
            $resolvedSelections.Add((Resolve-SelectedMediaRoot -Path $selection.Path -Label $selection.Label))
        } catch {
            Stop-WithMessage $_.Exception.Message
        }
    }
    $existingPrimary = $existing | Where-Object { $_.Id -eq "primary" } | Select-Object -First 1
    if ($existingPrimary) {
        for ($index = 1; $index -lt $resolvedSelections.Count; $index++) {
            if ($resolvedSelections[$index].HostPath.Equals(
                    $existingPrimary.HostPath,
                    [System.StringComparison]::OrdinalIgnoreCase
                )) {
                Stop-WithMessage "The registered primary media root must remain first so existing /media library paths stay stable. Omit it only for an explicit replacement."
            }
        }
    }
    for ($leftIndex = 0; $leftIndex -lt $resolvedSelections.Count; $leftIndex++) {
        $left = $resolvedSelections[$leftIndex].HostPath.TrimEnd('/')
        $leftPrefix = $left + "/"
        for ($rightIndex = $leftIndex + 1; $rightIndex -lt $resolvedSelections.Count; $rightIndex++) {
            $right = $resolvedSelections[$rightIndex].HostPath.TrimEnd('/')
            $rightPrefix = $right + "/"
            if ($left.Equals($right, [System.StringComparison]::OrdinalIgnoreCase) -or
                $left.StartsWith($rightPrefix, [System.StringComparison]::OrdinalIgnoreCase) -or
                $right.StartsWith($leftPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
                Stop-WithMessage "Approved media roots must be distinct and cannot contain one another."
            }
        }
        foreach ($entry in $ResolvedState.GetEnumerator()) {
            $state = $entry.Value.Replace('\', '/').TrimEnd('/')
            $statePrefix = $state + "/"
            if ($left.Equals($state, [System.StringComparison]::OrdinalIgnoreCase) -or
                $left.StartsWith($statePrefix, [System.StringComparison]::OrdinalIgnoreCase) -or
                $state.StartsWith($leftPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
                Stop-WithMessage "$($entry.Key) and an approved media root overlap. Runtime writes must remain isolated from source media."
            }
        }
    }

    $records = [System.Collections.Generic.List[object]]::new()
    $usedIds = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    for ($index = 0; $index -lt $resolvedSelections.Count; $index++) {
        $selection = $resolvedSelections[$index]
        $prior = $existing | Where-Object { $_.HostPath.Equals($selection.HostPath, [System.StringComparison]::OrdinalIgnoreCase) } | Select-Object -First 1
        if ($index -eq 0) {
            $id = "primary"
            $containerPath = "/media"
        } elseif ($prior -and $prior.Id -ne "primary") {
            $id = $prior.Id
            $containerPath = $prior.ContainerPath
        } else {
            do { $id = New-StableMediaRootId } while ($usedIds.Contains($id))
            $containerPath = "/media-roots/$id"
        }
        $null = $usedIds.Add($id)
        $displayName = if ($selection.LabelWasExplicit) {
            $selection.DisplayName
        } elseif ($prior) {
            $prior.DisplayName
        } else {
            $selection.DisplayName
        }
        $records.Add([pscustomobject]@{
            Id = $id
            DisplayName = $displayName
            ContainerPath = $containerPath
            HostPath = $selection.HostPath
        })
    }

    $definitions = @($records | ForEach-Object {
        [ordered]@{ id = $_.Id; display_name = $_.DisplayName; path = $_.ContainerPath }
    })
    $definitionsJson = ConvertTo-Json -InputObject $definitions -Compress -Depth 4
    $rootPaths = ($records | ForEach-Object { $_.ContainerPath }) -join ":"
    $environmentContent = [System.IO.File]::ReadAllText($EnvironmentFile)
    $environmentContent = Update-DotEnvContent $environmentContent ([ordered]@{
        MEDIA_PATH = (ConvertTo-DotEnvLiteral $records[0].HostPath)
        MEDIA_ROOTS = $rootPaths
        MEDIA_ROOT_DEFINITIONS = (ConvertTo-DotEnvLiteral $definitionsJson)
    })

    $overrideContent = $null
    if ($records.Count -gt 1) {
        $mounts = @($records | Select-Object -Skip 1 | ForEach-Object {
            [ordered]@{ type = "bind"; source = $_.HostPath; target = $_.ContainerPath; read_only = $true }
        })
        $override = [ordered]@{
            "x-bluereel-generated" = [ordered]@{ version = 1; purpose = "approved read-only media roots" }
            services = [ordered]@{
                backend = [ordered]@{ volumes = $mounts }
                worker = [ordered]@{ volumes = $mounts }
            }
        }
        $overrideContent = $GeneratedOverrideMarker + "`n" + (ConvertTo-Json -InputObject $override -Depth 8) + "`n"
    }

    $candidateEnvironment = Join-Path $RepositoryRoot (".env.media-roots.tmp." + [guid]::NewGuid().ToString("N"))
    $candidateOverride = Join-Path $RepositoryRoot ("compose.media-roots.tmp." + [guid]::NewGuid().ToString("N") + ".yml")
    try {
        [System.IO.File]::WriteAllText($candidateEnvironment, $environmentContent, [System.Text.UTF8Encoding]::new($false))
        $composeArguments = @("compose", "--env-file", $candidateEnvironment, "-f", $ComposeFile)
        if ($overrideContent) {
            [System.IO.File]::WriteAllText($candidateOverride, $overrideContent, [System.Text.UTF8Encoding]::new($false))
            $composeArguments += @("-f", $candidateOverride)
        }
        $composeArguments += @("config", "--quiet")
        & docker @composeArguments
        if ($LASTEXITCODE -ne 0) {
            Stop-WithMessage "Docker Compose rejected the proposed media-root configuration; existing local configuration was not changed."
        }
    } finally {
        if (Test-Path -LiteralPath $candidateEnvironment) { Remove-Item -LiteralPath $candidateEnvironment -Force }
        if (Test-Path -LiteralPath $candidateOverride) { Remove-Item -LiteralPath $candidateOverride -Force }
    }

    $registryLines = [System.Collections.Generic.List[string]]::new()
    $registryLines.Add($MediaRootRegistryHeader)
    foreach ($record in $records) {
        $registryLines.Add(($record.Id, $record.DisplayName, $record.ContainerPath, $record.HostPath) -join "`t")
    }
    Write-AtomicUtf8 $EnvironmentFile $environmentContent
    Write-AtomicUtf8 $MediaRootRegistryFile (($registryLines -join "`n") + "`n")
    if ($overrideContent) {
        Write-AtomicUtf8 $ComposeOverrideFile $overrideContent
    } elseif (Test-ManagedComposeOverride) {
        Remove-Item -LiteralPath $ComposeOverrideFile -Force
    }
    Write-Host "Approved media roots were configured. Adding or changing roots requires controlled container recreation."
    foreach ($record in $records) {
        Write-Host ("  {0}: {1} -> {2} (read-only)" -f $record.DisplayName, $record.HostPath, $record.ContainerPath)
    }
    return $true
}

function Test-PrivateBindAddress([string]$Address) {
    $parsed = $null
    if (-not [System.Net.IPAddress]::TryParse($Address, [ref]$parsed)) { return $false }
    if ([System.Net.IPAddress]::IsLoopback($parsed)) { return $true }
    if ($parsed.AddressFamily -ne [System.Net.Sockets.AddressFamily]::InterNetwork) { return $false }
    $octets = $parsed.GetAddressBytes()
    return ($octets[0] -eq 10) -or
        ($octets[0] -eq 172 -and $octets[1] -ge 16 -and $octets[1] -le 31) -or
        ($octets[0] -eq 192 -and $octets[1] -eq 168)
}

