foreach ($value in @($MediaPath)) {
    if (-not [string]::IsNullOrWhiteSpace($value)) { $SuppliedMediaPaths.Add($value) }
}
$SuppliedMediaLabels = [System.Collections.Generic.List[string]]::new()
foreach ($value in @($MediaLabel)) {
    if ($null -ne $value) { $SuppliedMediaLabels.Add($value) }
